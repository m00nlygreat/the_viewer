for (const [name, grammar] of Object.entries({
  bash, c, cpp, csharp, css, diff, dockerfile, go, ini, java, javascript, json, kotlin, markdown,
  php, powershell, python, ruby, rust, scss, sql, typescript, xml, yaml
})) {
  hljs.registerLanguage(name, grammar)
}

export function highlightMarkdownCode(source: string, language: string | null): string {
  if (!language) return escapeHtml(source)
  try {
    return hljs.highlight(source, { language, ignoreIllegals: true }).value
  } catch {
    return escapeHtml(source)
  }
}

function escapeHtml(source: string): string {
  return source.replace(/[&<>"']/gu, (character) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#x27;'
  })[character]!)
}
